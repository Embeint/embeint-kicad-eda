"""Real-process refusal controls for libs.core.application.thin.replacement.p001.

Replays fixtures/wx-stl-compat-controls.jsonl (generated by
rust/kicad-wx-stl-compat-shim/generate_cases.py) against each binary given: the C++ oracle
and/or the Rust shim. Every malformed or out-of-contract request must be refused with
exactly the recorded invalid_input message, and the same process must then answer a real
insertion and a real conversion. These are refusal controls, never reference results.
"""
import json
from pathlib import Path
import subprocess
import sys

UNIT = "libs.core.application.thin.replacement.p001"
CONTROLS = Path(__file__).parent / "fixtures/wx-stl-compat-controls.jsonl"
STREAM = {"state": [], "exceptions": [], "flags": ["dec", "skipws"], "width": 0, "precision": 6,
          "fill": 32, "thousands_sep": 44, "grouping": [], "capacity": None, "sync_fails": False}
CONTINUATIONS = [
    ({"op": "insert_size", "value": [-7, 2147483647], "stream": STREAM},
     {"bytes": ' width="-7" height="2147483647"'.encode().hex(), "exceptions": [], "fill": 32,
      "flags": ["dec", "skipws"], "outcome": "returned", "precision": 6, "same_stream": True, "state": [],
      "sync_calls": 0, "width": 0}),
    # An embedded NUL is kept by the explicit-length constructor.
    ({"op": "to_wx_string", "ctype": "C.UTF-8", "view": "c3a90061"}, {"units": [0xE9, 0, 0x61]}),
]


def check(binary):
    controls = [json.loads(line) for line in CONTROLS.read_text(encoding="utf-8").splitlines()]
    requests, expected = [], []
    for index, control in enumerate(controls):
        request = control["request"]
        requests.append(request)
        expected.append({"unit": UNIT, "case": request["case"], "error": control["error"]})
        for step, (value_input, result) in enumerate(CONTINUATIONS):
            case = f"continuation-{index}-{step}"
            requests.append({"unit": UNIT, "case": case, "input": value_input})
            expected.append({"unit": UNIT, "case": case, "result": result})
    payload = "".join(json.dumps(r, separators=(",", ":")) + "\n" for r in requests)
    process = subprocess.run([binary], input=payload.encode(), capture_output=True, timeout=60, check=True)
    actual = [json.loads(line) for line in process.stdout.decode().splitlines()]
    if len(actual) != len(expected):
        raise AssertionError(f"reply count {len(actual)} != {len(expected)}")
    for index, (got, want) in enumerate(zip(actual, expected)):
        if got != want:
            raise AssertionError(f"{binary} line {index + 1}: {got} != {want}")
    print(f"{binary}: {len(controls)} refusals, each followed by successful continuations")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("usage: test_wx_stl_compat_inputs.py ORACLE [RUST_SHIM]")
    for binary in sys.argv[1:]:
        check(binary)
