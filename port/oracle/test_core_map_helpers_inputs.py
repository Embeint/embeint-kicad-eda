"""Real-process refusal controls for
libs.core.include.core.application.thin.replacement.p001 (map_helpers.h).

Replays fixtures/core-map-helpers-controls.jsonl (generated by
rust/kicad-map-helpers-shim/generate_cases.py) against each binary given: the C++
oracle and/or the Rust shim. Every control must be refused with exactly the recorded
invalid_input message, and the process must still answer a real lookup after each
refusal. These are malformed-request controls, never reference results.
"""
import json
from pathlib import Path
import subprocess
import sys

UNIT = "libs.core.include.core.application.thin.replacement.p001"
CONTROLS = Path(__file__).parent / "fixtures/core-map-helpers-controls.jsonl"
# get_def( map, wxS( "TYPE" ) ) on an LTspice-style attribute map.
CONTINUATION = {"op": "get_def_wx", "map": [[[84, 89, 80, 69], [114, 101, 115]]],
                "key": [84, 89, 80, 69]}
CONTINUED = {"value": [114, 101, 115]}


def check(binary):
    controls = [json.loads(line) for line in CONTROLS.read_text(encoding="utf-8").splitlines()]
    requests, expected = [], []
    for index, control in enumerate(controls):
        request = control["request"]
        requests.append(request)
        expected.append({"unit": UNIT, "case": request["case"], "error": control["error"]})
        case = f"continuation-{index}"
        requests.append({"unit": UNIT, "case": case, "input": CONTINUATION})
        expected.append({"unit": UNIT, "case": case, "result": CONTINUED})
    payload = "".join(json.dumps(r, separators=(",", ":"), ensure_ascii=False) + "\n" for r in requests)
    process = subprocess.run([binary], input=payload.encode(), capture_output=True, timeout=120, check=True)
    actual = [json.loads(line) for line in process.stdout.decode().splitlines()]
    if len(actual) != len(expected):
        raise AssertionError(f"reply count {len(actual)} != {len(expected)}")
    for index, (got, want) in enumerate(zip(actual, expected)):
        if got != want:
            raise AssertionError(f"{binary} line {index + 1}: {str(got)[:400]} != {str(want)[:400]}")
    print(f"{binary}: {len(controls)} refusals, each followed by a successful continuation")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("usage: test_core_map_helpers_inputs.py ORACLE [RUST_SHIM]")
    for binary in sys.argv[1:]:
        check(binary)
