"""Real-process refusal controls for libs.core.include.core.application.pure.p001.

Replays fixtures/core-include-p001-controls.jsonl (generated by
rust/kicad-core-include-shim/generate_cases.py) against each binary given: the C++
oracle and/or the Rust shim. Every control must be refused with exactly the recorded
invalid_input message, and the process must still answer a real operation after each
refusal. These are domain controls (undefined or non-terminating reference behaviour,
harness limits and malformed requests), never reference results.
"""
import json
from pathlib import Path
import subprocess
import sys

UNIT = "libs.core.include.core.application.pure.p001"
CONTROLS = Path(__file__).parent / "fixtures/core-include-p001-controls.jsonl"
CONTINUATION = {"op": "union_find", "count": 3, "steps": [{"op": "unite", "a": 2, "b": 1}]}
CONTINUED = {"constructed": True, "results": [True], "components": 2, "parents": [0, 1, 1]}


def check(binary):
    controls = [json.loads(line) for line in CONTROLS.read_text(encoding="utf-8").splitlines()]
    requests, expected = [], []
    for index, control in enumerate(controls):
        request = control["request"]
        requests.append(request)
        expected.append({"unit": UNIT, "case": request["case"], "error": control["error"]})
        case = f"continuation-{index}"
        requests.append({"unit": UNIT, "case": case, "input": CONTINUATION})
        expected.append({"unit": UNIT, "case": case, "result": CONTINUED})
    # A refusal inside a profile script must leave the scripted clock disarmed and
    # empty: the next script reads exactly its own values.
    clock = {"op": "profile", "clock": [3, 1003],
             "steps": [{"op": "timer_default", "timer": 0}, {"op": "timer_msecs", "timer": 0}]}
    requests.append({"unit": UNIT, "case": "clock-after-refusals", "input": clock})
    expected.append({"unit": UNIT, "case": "clock-after-refusals",
                     "result": {"results": [None, "3f50624dd2f1a9fc"], "clock_calls": 2}})
    payload = "".join(json.dumps(r, separators=(",", ":"), ensure_ascii=False) + "\n" for r in requests)
    process = subprocess.run([binary], input=payload.encode(), capture_output=True, timeout=120, check=True)
    actual = [json.loads(line) for line in process.stdout.decode().splitlines()]
    if len(actual) != len(expected):
        raise AssertionError(f"reply count {len(actual)} != {len(expected)}")
    for index, (got, want) in enumerate(zip(actual, expected)):
        if got != want:
            raise AssertionError(f"{binary} line {index + 1}: {str(got)[:400]} != {str(want)[:400]}")
    print(f"{binary}: {len(controls)} refusals, each followed by a successful continuation")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("usage: test_core_include_p001_inputs.py ORACLE [RUST_SHIM]")
    for binary in sys.argv[1:]:
        check(binary)
