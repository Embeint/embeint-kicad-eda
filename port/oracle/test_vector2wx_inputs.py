"""Real-process refusal controls for libs.kimath.include.math.application.thin.replacement.p001.

Replays fixtures/vector2wx-controls.jsonl (generated by
rust/kicad-vector2wx-shim/generate_cases.py) against each binary given: the C++ oracle
and/or the Rust shim. Every malformed request must be refused with exactly the recorded
invalid_input message, and the same process must then answer a real conversion. These
are malformed-request controls, never reference results.
"""
import json
from pathlib import Path
import subprocess
import sys

UNIT = "libs.kimath.include.math.application.thin.replacement.p001"
CONTROLS = Path(__file__).parent / "fixtures/vector2wx-controls.jsonl"
# INT_MAX and a negative value both survive the conversion to double exactly.
CONTINUATION = {"op": "to_vector2d_point", "value": [-7, 2147483647]}
CONTINUED = {"x": "c01c000000000000", "y": "41dfffffffc00000"}


def check(binary):
    controls = [json.loads(line) for line in CONTROLS.read_text(encoding="utf-8").splitlines()]
    requests, expected = [], []
    for index, control in enumerate(controls):
        request = control["request"]
        requests.append(request)
        expected.append({"unit": UNIT, "case": request["case"], "error": control["error"]})
        case = f"continuation-{index}"
        requests.append({"unit": UNIT, "case": case, "input": CONTINUATION})
        expected.append({"unit": UNIT, "case": case, "result": CONTINUED})
    payload = "".join(json.dumps(r, separators=(",", ":")) + "\n" for r in requests)
    process = subprocess.run([binary], input=payload.encode(), capture_output=True, timeout=60, check=True)
    actual = [json.loads(line) for line in process.stdout.decode().splitlines()]
    if len(actual) != len(expected):
        raise AssertionError(f"reply count {len(actual)} != {len(expected)}")
    for index, (got, want) in enumerate(zip(actual, expected)):
        if got != want:
            raise AssertionError(f"{binary} line {index + 1}: {got} != {want}")
    print(f"{binary}: {len(controls)} refusals, each followed by a successful continuation")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("usage: test_vector2wx_inputs.py ORACLE [RUST_SHIM]")
    for binary in sys.argv[1:]:
        check(binary)
