"""Real-process refusal controls for libs.kiplatform.os.unix.application.ui.p001.

Replays fixtures/kiplatform-unix-ui-p001-controls.jsonl (generated by
rust/kicad-kiplatform-unix-shim/generate_cases.py) against each binary given: the C++ oracle
and/or the Rust shim. Every control must be refused with exactly the recorded invalid_input
message, and the process must still answer successful requests after each refusal (the fakes
are disarmed and the scripted converters, log target and assertion handler restored). The
controls are malformed requests and inputs whose reference evaluation is undefined, never
reference results.
"""
import json
from pathlib import Path
import subprocess
import sys

UNIT = "libs.kiplatform.os.unix.application.ui.p001"
CONTROLS = Path(__file__).parent / "fixtures/kiplatform-unix-ui-p001-controls.jsonl"
KEY = [75, 73, 67, 65, 68, 95, 83, 72, 79, 87, 95, 71, 84, 75, 95, 77, 69, 83, 83, 65, 71, 69, 83]
CONTINUATIONS = (
    ({"op": "trivial", "args": {"function": "attach_console", "flag": True}, "host": {}},
     {"returned": True, "calls": []}),
    ({"op": "app_init", "args": {}, "host": {"env": {"KICAD_SHOW_GTK_MESSAGES": [49]}}},
     {"returned": True, "calls": [{"fn": "wxGetEnv", "var": KEY, "value_ptr": True}]}),
    ({"op": "io_is_file_hidden", "args": {"path": [47, 46, 120]}, "host": {}},
     {"returned": True, "calls": []}),
)


def check(binary):
    controls = [json.loads(line) for line in CONTROLS.read_text(encoding="utf-8").splitlines()]
    requests, expected = [], []
    for index, control in enumerate(controls):
        request = control["request"]
        requests.append(request)
        expected.append({"unit": UNIT, "case": request["case"], "error": control["error"]})
        payload, result = CONTINUATIONS[index % len(CONTINUATIONS)]
        case = f"continuation-{index}"
        requests.append({"unit": UNIT, "case": case, "input": payload})
        expected.append({"unit": UNIT, "case": case, "result": result})
    payload = "".join(json.dumps(r, separators=(",", ":"), ensure_ascii=False) + "\n" for r in requests)
    process = subprocess.run([binary], input=payload.encode(), capture_output=True, timeout=120,
                             check=True)
    actual = [json.loads(line) for line in process.stdout.decode().splitlines()]
    if len(actual) != len(expected):
        raise AssertionError(f"reply count {len(actual)} != {len(expected)}")
    for index, (got, want) in enumerate(zip(actual, expected)):
        if got != want:
            raise AssertionError(f"{binary} line {index + 1}: {str(got)[:400]} != {str(want)[:400]}")
    print(f"{binary}: {len(controls)} refusals, each followed by a successful continuation")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("usage: test_kiplatform_unix_ui_p001_inputs.py ORACLE [RUST_SHIM]")
    for binary in sys.argv[1:]:
        check(binary)
