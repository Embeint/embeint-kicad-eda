"""Real-process refusal controls for libs.kiplatform.os.unix.application.pure.p001.

Replays fixtures/kiplatform-unix-p001-controls.jsonl (generated by
rust/kicad-kiplatform-sysinfo-shim/generate_cases.py) against each binary given:
the C++ oracle and/or the Rust shim. Every control must be refused with exactly the
recorded invalid_input message, and the process must still answer a real
SYSINFO lifecycle on a populated fixture after each refusal. These are malformed
requests, never reference results.
"""
import json
from pathlib import Path
import subprocess
import sys

UNIT = "libs.kiplatform.os.unix.application.pure.p001"
CONTROLS = Path(__file__).parent / "fixtures/kiplatform-unix-p001-controls.jsonl"
MEMORY = {"usage": 9, "total_physical": 1, "free_physical": 2, "total_paging": 3,
          "free_paging": 4, "total_virtual": 5, "free_virtual": 18446744073709551615}
CPUS = [{"name": "00ff", "manufacturer": "", "number_cores": 4294967295, "number_logical": 1}]
GPUS = [{"name": "", "memory_size": -9223372036854775808, "driver_version": "c328",
         "manufacturer": "41"}]
STATE = {"memory": MEMORY, "cpus": CPUS, "gpus": GPUS}
CONTINUATION = {"op": "sysinfo", "memory": MEMORY, "cpus": CPUS, "gpus": GPUS,
                "steps": ["memory", "reconstruct", "cpu", "gpu"]}
CONTINUED = {
    "before": STATE,
    "steps": [
        {"step": "memory", "returned": False, "state": STATE, "storage_unchanged": True},
        {"step": "reconstruct", "state": STATE, "storage_unchanged": True},
        {"step": "cpu", "returned": False, "state": STATE, "storage_unchanged": True},
        {"step": "gpu", "returned": False, "state": STATE, "storage_unchanged": True},
    ],
    "after_destroy": {"state": STATE, "storage_unchanged": True},
}


def check(binary):
    controls = [json.loads(line) for line in CONTROLS.read_text(encoding="utf-8").splitlines()]
    requests, expected = [], []
    for index, control in enumerate(controls):
        request = control["request"]
        requests.append(request)
        expected.append({"unit": UNIT, "case": request["case"], "error": control["error"]})
        case = f"continuation-{index}"
        requests.append({"unit": UNIT, "case": case, "input": CONTINUATION})
        expected.append({"unit": UNIT, "case": case, "result": CONTINUED})
    requests.append({"unit": UNIT, "case": "driver-after-refusals",
                     "input": {"op": "valid_3dconnexion_driver_version"}})
    expected.append({"unit": UNIT, "case": "driver-after-refusals", "result": {"returned": False}})
    payload = "".join(json.dumps(r, separators=(",", ":"), ensure_ascii=False) + "\n" for r in requests)
    process = subprocess.run([binary], input=payload.encode(), capture_output=True, timeout=60, check=True)
    actual = [json.loads(line) for line in process.stdout.decode().splitlines()]
    if len(actual) != len(expected):
        raise AssertionError(f"reply count {len(actual)} != {len(expected)}")
    for index, (got, want) in enumerate(zip(actual, expected)):
        if got != want:
            raise AssertionError(f"{binary} line {index + 1}: {str(got)[:400]} != {str(want)[:400]}")
    print(f"{binary}: {len(controls)} refusals, each followed by a successful continuation")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("usage: test_kiplatform_unix_p001_inputs.py ORACLE [RUST_SHIM]")
    for binary in sys.argv[1:]:
        check(binary)
