"""Real-process refusal controls for libs.core.application.pure.p001.

Replays fixtures/core-p001-controls.jsonl (generated by
rust/kicad-core-shim/generate_cases.py) against each binary given: the C++ oracle
and/or the Rust shim. Every control must be refused with exactly the recorded
invalid_input message, and the process must still answer a real operation after
each refusal. These are domain controls (undefined or non-terminating reference
behaviour and malformed requests), never reference results.
"""
import json
from pathlib import Path
import subprocess
import sys

UNIT = "libs.core.application.pure.p001"
CONTROLS = Path(__file__).parent / "fixtures/core-p001-controls.jsonl"
CONTINUATION = {"op": "decode", "input": "54574675"}  # "TWFu"
CONTINUED = {"output": "4d616e"}  # "Man"


def check(binary):
    controls = [json.loads(line) for line in CONTROLS.read_text(encoding="utf-8").splitlines()]
    requests, expected = [], []
    for index, control in enumerate(controls):
        request = control["request"]
        requests.append(request)
        expected.append({"unit": UNIT, "case": request["case"], "error": control["error"]})
        case = f"continuation-{index}"
        requests.append({"unit": UNIT, "case": case, "input": CONTINUATION})
        expected.append({"unit": UNIT, "case": case, "result": CONTINUED})
    # A clock refusal must leave the clock script disarmed: the continuation after it
    # is a real reading that must still succeed with exactly one scripted read.
    requests.append({"unit": UNIT, "case": "clock-after-refusals",
                     "input": {"op": "running_micro_secs", "tv_sec": 3, "tv_nsec": 4000}})
    expected.append({"unit": UNIT, "case": "clock-after-refusals",
                     "result": {"value": 3000004, "clock_calls": 1, "clock_id": 1}})
    payload = "".join(json.dumps(r, separators=(",", ":"), ensure_ascii=False) + "\n" for r in requests)
    process = subprocess.run([binary], input=payload.encode(), capture_output=True, timeout=120, check=True)
    actual = [json.loads(line) for line in process.stdout.decode().splitlines()]
    if len(actual) != len(expected):
        raise AssertionError(f"reply count {len(actual)} != {len(expected)}")
    for index, (got, want) in enumerate(zip(actual, expected)):
        if got != want:
            raise AssertionError(f"{binary} line {index + 1}: {str(got)[:400]} != {str(want)[:400]}")
    print(f"{binary}: {len(controls)} refusals, each followed by a successful continuation")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("usage: test_core_p001_inputs.py ORACLE [RUST_SHIM]")
    for binary in sys.argv[1:]:
        check(binary)
