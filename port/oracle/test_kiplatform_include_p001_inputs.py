"""Real-process refusal controls for libs.kiplatform.include.kiplatform.application.pure.p001.

Replays fixtures/kiplatform-include-p001-controls.jsonl (generated by
rust/kicad-kiplatform-include-shim/generate_cases.py) against each binary given: the
C++ oracle and/or the Rust shim. Every control must be refused with exactly the
recorded invalid_input message, and the process must still answer successful requests
after each refusal: a handler lifecycle and a default-argument call through the pinned
header. These are malformed requests, never reference results.
"""
import json
from pathlib import Path
import subprocess
import sys

UNIT = "libs.kiplatform.include.kiplatform.application.pure.p001"
CONTROLS = Path(__file__).parent / "fixtures/kiplatform-include-p001-controls.jsonl"
CONTINUATIONS = (
    ({"op": "touchpad_handlers",
      "steps": [{"action": "create", "slot": 1}, {"action": "create", "slot": 1}]},
     {"events": [{"event": "construct", "id": 0}, {"event": "construct", "id": 1},
                 {"event": "destroy", "id": 0}, {"event": "destroy", "id": 1}]}),
    ({"op": "default_arguments", "function": "atomic_rename", "strings": [[97], [98, 0]],
      "explicit": False, "returned": True},
     {"strings": [[97], [98, 0]], "flags": {"error_is_null": True}, "returned": True}),
)


def check(binary):
    controls = [json.loads(line) for line in CONTROLS.read_text(encoding="utf-8").splitlines()]
    requests, expected = [], []
    for index, control in enumerate(controls):
        request = control["request"]
        requests.append(request)
        expected.append({"unit": UNIT, "case": request["case"], "error": control["error"]})
        payload, result = CONTINUATIONS[index % len(CONTINUATIONS)]
        case = f"continuation-{index}"
        requests.append({"unit": UNIT, "case": case, "input": payload})
        expected.append({"unit": UNIT, "case": case, "result": result})
    payload = "".join(json.dumps(r, separators=(",", ":"), ensure_ascii=False) + "\n" for r in requests)
    process = subprocess.run([binary], input=payload.encode(), capture_output=True, timeout=60, check=True)
    actual = [json.loads(line) for line in process.stdout.decode().splitlines()]
    if len(actual) != len(expected):
        raise AssertionError(f"reply count {len(actual)} != {len(expected)}")
    for index, (got, want) in enumerate(zip(actual, expected)):
        if got != want:
            raise AssertionError(f"{binary} line {index + 1}: {str(got)[:400]} != {str(want)[:400]}")
    print(f"{binary}: {len(controls)} refusals, each followed by a successful continuation")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("usage: test_kiplatform_include_p001_inputs.py ORACLE [RUST_SHIM]")
    for binary in sys.argv[1:]:
        check(binary)
