"""Real-process refusal controls for libs.kiplatform.os.unix.application.thin.replacement.p001.

Replays fixtures/kiplatform-policy-controls.jsonl (generated by
rust/kicad-kiplatform-shim/generate_cases.py) against each binary given: the C++
oracle and/or the Rust shim. Every raw control line must be refused with exactly
the recorded envelope, and the process must still answer a genuine call after each
refusal. With two binaries, every reply must also be identical across them. These
are malformed-request controls, never reference results.
"""
import json
from pathlib import Path
import subprocess
import sys

UNIT = "libs.kiplatform.os.unix.application.thin.replacement.p001"
CONTROLS = Path(__file__).parent / "fixtures/kiplatform-policy-controls.jsonl"
OPS = ("get_policy_bool", "get_policy_enum_uint")
CONTINUED = {"get_policy_bool": "NOT_CONFIGURED", "get_policy_enum_uint": None}


def check(binary):
    controls = [json.loads(line) for line in CONTROLS.read_text(encoding="utf-8").splitlines()]
    lines, expected = [], []
    for index, control in enumerate(controls):
        lines.append(control["line"])
        expected.append(control["reply"])
        op = OPS[index % 2]
        case = f"continuation-{index}"
        lines.append(json.dumps({"unit": UNIT, "case": case, "input": {"op": op, "key": [80, 0, 77]}}))
        expected.append({"unit": UNIT, "case": case,
                         "result": {"key_length": 3, "value": CONTINUED[op]}})
    payload = "".join(line + "\n" for line in lines)
    process = subprocess.run([binary], input=payload.encode(), capture_output=True, timeout=60, check=True)
    actual = [json.loads(line) for line in process.stdout.decode().splitlines()]
    if len(actual) != len(expected):
        raise AssertionError(f"reply count {len(actual)} != {len(expected)}")
    for index, (got, want) in enumerate(zip(actual, expected)):
        if got != want:
            raise AssertionError(f"{binary} line {index + 1}: {str(got)[:400]} != {str(want)[:400]}")
    print(f"{binary}: {len(controls)} refusals, each followed by a successful continuation")
    return process.stdout


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("usage: test_kiplatform_policy_inputs.py ORACLE [RUST_SHIM]")
    outputs = [check(binary) for binary in sys.argv[1:]]
    if len(outputs) == 2 and outputs[0] != outputs[1]:
        raise AssertionError("oracle and shim replies differ byte for byte")
