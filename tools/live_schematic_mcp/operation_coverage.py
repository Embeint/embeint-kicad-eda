"""Offline native-registration audit and operation matrix. Never connects to KiCad."""

import argparse
import ast
from dataclasses import asdict, dataclass, replace
import importlib
import json
from pathlib import Path
import re
import sys


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
DECISIONS = HERE / "operation_decisions.json"
NATIVE_TREES = ("common", "include", "eeschema", "pcbnew", "kicad")
STATUSES = {"supported", "deferred", "internal", "interactive"}
IMPLEMENTATIONS = {"implemented", "conditional", "stub"}
UNDO = {"not_applicable", "editor_commit", "standalone", "history", "none", "unknown"}

# Mask comments and literals without changing offsets, so evidence retains source line numbers.
CPP_NONCODE = re.compile(
    r'R"(?P<tag>[^ ()\\\t\r\n]{0,16})\(.*?\)(?P=tag)"'
    r'|//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'',
    re.DOTALL,
)
REGISTRATION = re.compile(
    r"\bregisterHandler\s*<\s*([\w:]+)\s*,\s*([\w:]+)\s*>\s*\(\s*"
    r"&\s*(API_HANDLER\w*)\s*::\s*(\w+)\s*(?:,\s*(true|false)\s*)?\)\s*;"
)
INHERITANCE = re.compile(
    r"\bclass\s+(?:\w+_API\s+)?(API_HANDLER\w*)\s*:\s*public\s+(API_HANDLER\w*)\s*\{"
)


class CoverageError(ValueError):
    pass


def mask_cpp(source):
    return CPP_NONCODE.sub(lambda m: re.sub(r"[^\n]", " ", m.group()), source)


@dataclass(frozen=True)
class Registration:
    owner: str
    request: str
    response: str
    method: str
    source: str
    line: int
    allowed_during_task: bool
    implementation_source: str = ""

    @property
    def key(self):
        return f"{self.owner}/{self.request}"


def protocol_messages():
    """Resolve names from protocols regenerated by generate_proto.py, not a version guess."""
    generated = HERE / "_generated"
    files = sorted(generated.rglob("*_pb2.py"))
    if not files:
        raise CoverageError("Run generate_proto.py before checking operation coverage")
    sys.path.insert(0, str(generated))
    messages = {}

    def collect(descriptor):
        messages[descriptor.full_name] = descriptor
        for nested in descriptor.nested_types:
            collect(nested)

    for path in files:
        module = importlib.import_module(".".join(path.relative_to(generated).with_suffix("").parts))
        for descriptor in module.DESCRIPTOR.message_types_by_name.values():
            collect(descriptor)
    from google.protobuf import empty_pb2

    collect(empty_pb2.Empty.DESCRIPTOR)
    return messages


def resolve_cpp_type(name, messages):
    # C++ uses namespace imports from both .cpp and inherited headers. Only accept a
    # unique suffix; ambiguity requires an explicit parser update, never a best guess.
    suffix = name.removeprefix("::").replace("::", ".")
    candidates = [full for full in messages if full == suffix or full.endswith("." + suffix)]
    if len(candidates) != 1:
        raise CoverageError(f"Cannot uniquely resolve C++ protobuf type {name}: {candidates}")
    return candidates[0]


def parse_registrations(source, path, messages):
    code = mask_cpp(source)
    matches = list(REGISTRATION.finditer(code))
    starts = {m.start() for m in matches}
    for token in re.finditer(r"\bregisterHandler\s*<", code):
        if token.start() not in starts:
            line = code.count("\n", 0, token.start()) + 1
            raise CoverageError(f"Unparsed registerHandler at {path}:{line}; extend the audit parser")
    return [Registration(
        owner=m[3], request=resolve_cpp_type(m[1], messages),
        response=resolve_cpp_type(m[2], messages), method=m[4], source=str(path),
        line=code.count("\n", 0, m.start()) + 1, allowed_during_task=m[5] == "true",
    ) for m in matches]


def audit_native(root, messages):
    registrations = {}
    parents = {}
    methods = {}
    for tree in NATIVE_TREES:
        for path in sorted((root / tree).rglob("*")):
            if path.suffix not in {".cpp", ".h"}:
                continue
            source = path.read_text(encoding="utf-8")
            if "API_HANDLER" not in source and "registerHandler" not in source:
                continue
            relative = path.relative_to(root).as_posix()
            for registration in parse_registrations(source, relative, messages):
                if registration.key in registrations:
                    raise CoverageError(f"Duplicate native registration: {registration.key}")
                registrations[registration.key] = registration
            code = mask_cpp(source)
            for child, parent in INHERITANCE.findall(code):
                if child in parents:
                    raise CoverageError(f"Duplicate native class: {child}")
                parents[child] = parent
            for method in re.finditer(r"\b(API_HANDLER\w*::\w+)\s*\([^;{}]*\)\s*(?:const\s*)?\{", code):
                methods[method[1]] = f"{relative}:{code.count(chr(10), 0, method.start()) + 1}"
    if not registrations:
        raise CoverageError("No native registrations found; check the repository root")
    for key, registration in registrations.items():
        candidates = [f"{owner}::{registration.method}"
                      for owner in lineage(registration.owner, parents)]
        method = next((candidate for candidate in candidates if candidate in methods), None)
        if method is None:
            raise CoverageError(f"Cannot locate native implementation: {candidates}")
        registrations[key] = replace(registration, implementation_source=methods[method])
    return registrations, parents


def lineage(owner, parents):
    chain = []
    while owner != "API_HANDLER":
        if owner in chain or owner not in parents:
            raise CoverageError(f"Unknown or cyclic handler inheritance: {chain + [owner]}")
        chain.append(owner)
        owner = parents[owner]
    return chain


def tool_names(path):
    tree = ast.parse(path.read_text(encoding="utf-8"))
    return {node.name for node in tree.body
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
            and any(isinstance(decorator, ast.Call)
                    and isinstance(decorator.func, ast.Attribute)
                    and isinstance(decorator.func.value, ast.Name)
                    and decorator.func.value.id == "mcp" and decorator.func.attr == "tool"
                    for decorator in node.decorator_list)}


def load_decisions(path=DECISIONS):
    def unique_keys(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise CoverageError(f"Duplicate decision key: {key}")
            result[key] = value
        return result

    return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique_keys)


def validate_decisions(native, parents, data, commands, tools):
    """Require an intentional decision for every owner/request pair, including omissions."""
    errors = []
    evidence_functions = {}
    decisions = data["operations"]
    if data.get("matrix_version") != 1:
        errors.append("Unknown decision matrix version")
    if set(data["surfaces"]) != {"manager", "schematic", "pcb", "symbol", "footprint"}:
        errors.append("Expected explicit decisions for all five desktop surfaces")
    for key in sorted(native.keys() - decisions.keys()):
        errors.append(f"Missing native decision: {key}")
    for key in sorted(decisions.keys() - native.keys()):
        errors.append(f"Stale native decision: {key}")
    covered_owners = set()
    for surface, definition in data["surfaces"].items():
        if not definition["document"] or not definition["registration_notes"]:
            errors.append(f"Missing surface requirements: {surface}")
        for owner in definition["handlers"]:
            covered_owners.update(lineage(owner, parents))
    for owner in sorted(parents.keys() - covered_owners):
        errors.append(f"No surface decision for handler class: {owner}")
    for key, registration in sorted(native.items()):
        if registration.owner not in covered_owners:
            errors.append(f"No surface decision for handler class: {registration.owner}")
        if key not in decisions:
            continue
        entry = decisions[key]
        for field, allowed in (("decision", STATUSES), ("implementation", IMPLEMENTATIONS),
                               ("undo", UNDO)):
            if entry.get(field) not in allowed:
                errors.append(f"Invalid {field}: {key}")
        for field in ("document", "disk_effects", "notes", "registration_condition"):
            if not isinstance(entry.get(field), str) or not entry[field].strip():
                errors.append(f"Missing {field}: {key}")
        if entry.get("implementation") == "stub" and entry.get("decision") == "supported":
            errors.append(f"Stub cannot be supported: {key}")
        for field in ("typed_tools", "offline_tests"):
            if not isinstance(entry.get(field), list):
                errors.append(f"Missing explicit {field} list: {key}")
        for name in entry.get("typed_tools") or []:
            if name not in tools:
                errors.append(f"Stale typed tool {name}: {key}")
        for surface, override in entry.get("surface_overrides", {}).items():
            if surface not in data["surfaces"]:
                errors.append(f"Unknown override surface {surface}: {key}")
                continue
            owners = {owner for handler in data["surfaces"][surface]["handlers"]
                      for owner in lineage(handler, parents)}
            if registration.owner not in owners or not override.get("notes"):
                errors.append(f"Stale or unexplained surface override {surface}: {key}")
            for field, allowed in (("decision", STATUSES), ("implementation", IMPLEMENTATIONS),
                                   ("undo", UNDO)):
                if field in override and override[field] not in allowed:
                    errors.append(f"Invalid override {field} for {surface}: {key}")
            contextual = {**entry, **override}
            if contextual["implementation"] == "stub" and contextual["decision"] == "supported":
                errors.append(f"Stub cannot be supported for {surface}: {key}")
        for reference in entry.get("offline_tests") or []:
            filename, separator, name = reference.partition("::")
            path = HERE / filename
            if filename not in evidence_functions:
                evidence_functions[filename] = (
                    {node.name for node in ast.parse(path.read_text(encoding="utf-8")).body
                     if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))}
                    if path.parent == HERE and path.is_file() else set())
            if not separator or name not in evidence_functions[filename]:
                errors.append(f"Stale offline evidence {reference}: {key}")
        # A separately reviewed adapter addition is reflected automatically. It does not
        # promote a deferred native decision or confer undo/live qualification.
        if registration.request in commands:
            if commands[registration.request][0] != registration.response:
                errors.append(f"Adapter response differs from native response: {key}")
    if errors:
        raise CoverageError("\n".join(errors))


def build_matrix(root=ROOT, data=None, commands=None):
    messages = protocol_messages()
    native, parents = audit_native(root, messages)
    data = load_decisions() if data is None else data
    if commands is None:
        from commands import COMMANDS
        commands = COMMANDS
    validate_decisions(native, parents, data, commands, tool_names(HERE / "server.py"))
    rows = []
    for surface, definition in sorted(data["surfaces"].items()):
        owners = {owner for handler in definition["handlers"] for owner in lineage(handler, parents)}
        for key, registration in sorted(native.items()):
            if registration.owner not in owners:
                continue
            decision = data["operations"][key]
            generic = commands.get(registration.request)
            typed = decision["typed_tools"]
            if registration.owner in {"API_HANDLER_EDITOR", "API_HANDLER_BOARD"}:
                typed = [name for name in typed if name.startswith(f"live_{surface}_")
                         or name.startswith("live_editor_")]
            rows.append({
                "surface": surface, **asdict(registration), **decision,
                **decision.get("surface_overrides", {}).get(surface, {}),
                "typed_tools": typed,
                "surface_document": definition["document"],
                "surface_registration_notes": definition["registration_notes"],
                "generic_adapter": ({"command": registration.request, "response": generic[0],
                                     "kind": generic[1], "tool": "live_schematic_execute"}
                                    if generic else None),
                "evidence_kind": "static_source",
                "offline_evidence_kind": ("synthetic_test_references" if decision["offline_tests"]
                                          else "none_recorded"),
                "live_support_verified": False,
            })
    return {
        "matrix_version": 1,
        "decision_audited_base": data["audited_base"],
        "editor_connection_attempted": False,
        "live_support_verified": False,
        "native_registration_count": len(native),
        "native_request_count": len({r.request for r in native.values()}),
        "surface_row_count": len(rows),
        "surfaces": data["surfaces"],
        "operations": rows,
    }


def markdown_matrix(matrix):
    lines = ["# Native operation matrix", "",
             "Static registrations and curated decisions; no native/live qualification.", "",
             f"{matrix['native_registration_count']} owner/request registrations; "
             f"{matrix['native_request_count']} distinct requests; "
             f"{matrix['surface_row_count']} contextual rows.", ""]

    def cell(value):
        return str(value).replace("|", "\\|").replace("\n", " ")

    for surface, definition in matrix["surfaces"].items():
        lines.extend([f"## {surface}", "", definition["document"], "",
                      definition["registration_notes"], "",
                      "| Native request / owner / evidence | Decision / implementation | "
                      "Generic adapter / typed tools | Document / condition | Disk effects | Undo | Limits / offline evidence |",
                      "| --- | --- | --- | --- | --- | --- | --- |"])
        for row in matrix["operations"]:
            if row["surface"] != surface:
                continue
            adapter = row["generic_adapter"]
            mapping = (f"live_schematic_execute: {adapter['kind']}" if adapter else "No generic adapter")
            mapping += "; typed: " + (", ".join(row["typed_tools"]) or "none recorded")
            columns = [f"{row['request']} / {row['owner']}::{row['method']} / "
                       f"{row['source']}:{row['line']}; body: {row['implementation_source']}",
                       f"{row['decision']} / {row['implementation']}", mapping,
                       f"{row['document']} / {row['registration_condition']}",
                       row["disk_effects"], row["undo"],
                       row["notes"] + "; offline tests: " + (", ".join(row["offline_tests"]) or "none recorded")]
            lines.append("| " + " | ".join(cell(column) for column in columns) + " |")
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--format", choices=("check", "json", "markdown"), default="check")
    args = parser.parse_args()
    try:
        matrix = build_matrix()
    except CoverageError as error:
        parser.exit(1, f"Operation coverage failed:\n{error}\n")
    if args.format == "json":
        print(json.dumps(matrix, indent=2, sort_keys=True))
    elif args.format == "markdown":
        print(markdown_matrix(matrix))
    else:
        print(f"Operation coverage OK: {matrix['native_registration_count']} native registrations, "
              f"{matrix['surface_row_count']} contextual rows; live support unverified")


if __name__ == "__main__":
    main()
