/// E1..E192 use selectors 0..7; unknown selectors preserve KiCad's E1 fallback.
pub fn values(series: i32) -> Vec<u16> {
    let (table, skip): (&[u16], usize) = match series {
        0 => (&E24, 24),
        1 => (&E24, 8),
        2 => (&E24, 4),
        3 => (&E24, 2),
        4 => (&E24, 1),
        5 => (&E192, 4),
        6 => (&E192, 2),
        7 => (&E192, 1),
        _ => (&E24, 24),
    };
    table.iter().copied().step_by(skip).collect()
}

pub(crate) fn power10(exponent: f64) -> f64 {
    libm::pow(10.0, exponent)
}

/// Multiplication precedes division, including overflow in large decades.
pub fn in_decade(series: i32, exponent: i32) -> Vec<f64> {
    let multiplier = power10(f64::from(exponent));
    values(series)
        .into_iter()
        .map(|value| multiplier * f64::from(value) / 100.0)
        .collect()
}
