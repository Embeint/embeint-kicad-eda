// Embeds the bundled skills (tools/live_schematic_mcp/skills) into the server, so it serves the
// exact bytes of the checked-in files, with their hashes, without that directory at run time.
//
// The generated `skills.rs` is a table the runtime port of skills.py reads as Python reads the
// directory: every entry of the skills directory that Python's `is_dir()` accepts, and in each
// skill folder every entry whose name the `*.md` glob can match (on Windows, where Python's glob
// and file lookups ignore case, `.MD` too).  What Python's checks would refuse is recorded as
// unsafe instead of embedded: symlinks, junctions and non-files.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// A file name as UTF-8; skill names and files are refused at run time unless ASCII, so a name
/// that is not UTF-8 is a packaging mistake and stops the build.
fn name_of(path: &Path) -> String {
    path.file_name()
        .and_then(|name| name.to_str())
        .unwrap_or_else(|| panic!("skill path {} is not UTF-8", path.display()))
        .to_owned()
}

fn sorted_entries(dir: &Path) -> Vec<PathBuf> {
    let mut entries: Vec<PathBuf> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()))
        .map(|entry| entry.expect("directory entry").path())
        .collect();
    entries.sort();
    entries
}

/// Whether `path` is a real directory directly inside `parent` (Python's `is_symlink()` and
/// `resolve().parent` checks: a symlink or junction is unsafe).
fn is_plain_child(path: &Path, parent: &Path) -> bool {
    let symlink = fs::symlink_metadata(path).is_ok_and(|m| m.file_type().is_symlink());
    !symlink
        && path
            .canonicalize()
            .ok()
            .and_then(|real| real.parent().map(Path::to_path_buf))
            .is_some_and(|real_parent| real_parent == parent)
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let skills = manifest.join("../../tools/live_schematic_mcp/skills");
    // A changed, added or removed skill file rebuilds the server (cargo scans the directory)
    println!("cargo:rerun-if-changed={}", skills.display());
    let windows = env::var("CARGO_CFG_WINDOWS").is_ok();

    let mut code = String::from("// Generated by build.rs from tools/live_schematic_mcp/skills\n");
    code.push_str("pub static SKILLS: &[(&str, Folder)] = &[\n");
    // Python's skill_index() returns [] when the directory is missing; so does an empty table
    if let Some(root) = skills.canonicalize().ok().filter(|path| path.is_dir()) {
        for path in sorted_entries(&root) {
            // Python skips what is_dir() refuses (files, broken links)
            if !path.is_dir() {
                continue;
            }
            println!("cargo:rerun-if-changed={}", path.display());
            let name = name_of(&path);
            if !is_plain_child(&path, &root) {
                writeln!(code, "    ({name:?}, Folder::Unsafe),").expect("write");
                continue;
            }
            let real = path.canonicalize().expect("canonical skill folder");
            writeln!(code, "    ({name:?}, Folder::Dir(&[").expect("write");
            for file in sorted_entries(&real) {
                let file_name = name_of(&file);
                let markdown = if windows {
                    file_name.to_ascii_lowercase().ends_with(".md")
                } else {
                    file_name.ends_with(".md")
                };
                if !markdown {
                    continue;
                }
                println!("cargo:rerun-if-changed={}", file.display());
                let regular = fs::symlink_metadata(&file).is_ok_and(|m| m.file_type().is_file());
                if !regular || !is_plain_child(&file, &real) {
                    writeln!(code, "        ({file_name:?}, None),").expect("write");
                    continue;
                }
                let bytes = fs::read(&file)
                    .unwrap_or_else(|e| panic!("cannot read {}: {e}", file.display()));
                // The Python server decodes every file it serves as UTF-8; a skill file that is not
                // UTF-8 would fail there at run time, so it stops this build instead
                if std::str::from_utf8(&bytes).is_err() {
                    panic!("skill file {} is not UTF-8", file.display());
                }
                let source = file.to_str().expect("UTF-8 skill path");
                writeln!(
                    code,
                    "        ({file_name:?}, Some(include_bytes!({source:?}) as &[u8])),"
                )
                .expect("write");
            }
            code.push_str("    ])),\n");
        }
    }
    code.push_str("];\n");
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("skills.rs");
    fs::write(&out, code).expect("write the skill table");
}
