"""Live workflows for mcp_parity.py --live: both MCP servers through the same tool sequences.

live_parity.run calls run_workflows after its transaction and manufacturing checks.  Each
workflow runs once per server, in turn, through one MCP session that stays open for the whole
workflow, from the same document state.  Every tool call is recorded with its arguments and
result and, for an edit, the effect on KiCad: the complete items of the edited document
(schematic, board, library symbol or footprint) after the call, or the settings or saved library
file it changes.  The two recordings are compared call by call after normalisation, exactly
unless the step says otherwise.  Normalisation names what differs between runs by nature: ids
that existed before the workflow keep their value (both servers start from the same documents),
new ids (generated by KiCad or the server) are named in order of first appearance, with the
items of a document snapshot put in an order that does not depend on those ids; revisions and
operation ids are named the same way, and net codes are left out of document snapshots (KiCad
numbers nets in the order an update adds them, which changes from run to run).  The modes:

  png         2D views and the board's 3D view: identical pixels (and the same text content)
  png-size    kicad-cli's 3D render of a footprint: valid PNGs of the same size only, because
              kicad-cli does not repeat its own pixels from one run to the next (each such view is
              rendered twice per server to show it)
  route       routing and path checks, compared by behaviour (rust/MCP_PARITY_PLAN.md, Decisions
              2026-11-21): the same success or refusal, pads, layers, vias and conflicts, lengths
              within the tolerance of scenarios/board_design.py; the board after a route is compared
              exactly except the new tracks and vias, which are compared by net and layer
  route-drc   DRC and checks after a route: no violation of board_design.CHECK_CATEGORIES
              ["clearance"] for either server; violations that name a routed item are compared by
              type and severity, everything else exactly as for violations
  report      KiCad's update-from-schematic report as a set of lines; nets without net codes;
  violations  ERC, checks and DRC without the order of the violations or of a violation's items,
              and without a missing connection's pads: values KiCad orders by its own item order or
              by ids it or the servers generate at random (see each comparator)

The revision contract is checked on every edit: KiCad's undo (sent by the harness, not by the
server under test) restores the document exactly, redo restores the edit exactly, and no commit
stays open; a refused edit must leave the document unchanged.  The number of undo steps an edit
takes is recorded and must be the same for both servers.  Two kinds of edit are only checked for
open commits: Footprint Editor edits (KiCad opens a modal "Incomplete undo/redo" when a generated
footprint is undone) and the update from the schematic (KiCad's redo drops pad nets;
board_prepare records it once).  Settings that are not undoable (page, grid, origins, layers,
stackup, rules) are put back by the workflow itself; net classes and custom rules, which the tools
can only add to, by the harness.  Whatever happens in a workflow, the harness then undoes both
documents to their baseline and puts every setting back (layers, origins, pages, grids, stackup,
design rules, custom rules, net classes), checks that the documents and their settings are as
they were, and reruns ERC and DRC so both servers start with the same (not undoable) markers.

  schematic  place, connect pins and a pin to a net, move/rotate with drag, annotate, update from
             library, autoplace, symbol pins, netlist (hierarchy and sheet), ERC, page and
             set_page, select/highlight/focus, view, undo/redo
  libraries  scratch symbol and footprint libraries in a temporary folder (project scope): symbol
             new, add_pins (with replace), set_properties, summary, view, delete_items, save; footprint
             new, generate (several packages), set_properties, attach_step (a STEP written here),
             embedded files, summary, view, save, view_3d, check_model; search and get on the stock
             libraries; the editor grid in both library editors; unregistered and deleted afterwards
  board      update from schematic (dry run and real), placement, moves, outlines, via, zone and
             refill, graphics, keepouts, layers, origins, stackup, rules, custom rules, net classes,
             RF, impedance, path check, tracks, routing, checks, DRC, views, selection,
             delete_routing, undo/redo
  shared     the editor grid in the schematic and PCB editors; live_kicad_cli (version, ERC and DRC
             on the saved files, into a temporary folder, and a refused output path)

The scratch folder is new for every run.  live-demo's project library tables are put back
exactly (content, or absence) after the libraries workflow and again at the end.
"""

