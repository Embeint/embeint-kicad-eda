def run_workflows(checker, spec, doc, servers, server_env, endpoint, devnull, check, report, areas=None):
    from e2e_guard import test_board
    from client import board_document
    board = as_json(test_board(checker))
    board_doc = board_document(board)
    scratch = Path(tempfile.mkdtemp(prefix="embeint-parity-live-"))
    ctx = Context(checker, spec, doc, board, board_doc, scratch)
    tables = ctx.library_tables = library_tables(ctx)
    report.setdefault("workflows", {})
    report["workflow_scratch"] = str(scratch)
    try:
        ctx.original = state_of(ctx)
        for area, workflow, prepare, finish in AREAS:
            if areas and area not in areas:
                continue
            print(f"  -- {area}", flush=True)
            entries = report["workflows"].setdefault(area, {"calls": [], "contract": {}, "notes": []})
            ctx.entries = entries
            try:
                state = prepare(ctx, entries) if prepare else None
            except Exception as failure:  # noqa: BLE001 - reported; the next area still runs
                check(f"{area}: setup", False, f"{type(failure).__name__}: {failure}")
                continue
            try:
                run_area(area, workflow, finish, ctx, state, servers, server_env, endpoint, devnull, check, entries)
            except WorkflowAbort as failure:
                check(f"{area}: documents put back; the remaining areas run", False, str(failure))
                break
            finally:
                if state and "cleanup" in state:
                    try:
                        state["cleanup"]()
                    except Exception as failure:  # noqa: BLE001 - reported after restoring
                        check(f"{area}: setup removed again", False, f"{type(failure).__name__}: {failure}")
        report["workflow_summary"] = summarise(report["workflows"])
    finally:
        problems = final_cleanup(ctx, tables)
        check("scratch libraries unregistered, editors parked, project library tables put back exactly, "
              "scratch folder removed", not problems, "; ".join(problems))


def summarise(workflows):
    """Calls, tools and how each call was compared, by area and in total."""
    def count(calls):
        modes = {}
        for call in calls:
            modes[call.get("mode", "?")] = modes.get(call.get("mode", "?"), 0) + 1
        return {"calls": len(calls), "agreed": sum(bool(c.get("agree")) for c in calls),
                "tools": len({c["tool"] for c in calls}), "modes": dict(sorted(modes.items())),
                "effects_compared": sum(bool(c.get("effects_compared")) for c in calls),
                "identical_pixels": sum(bool(c.get("identical_pixels")) for c in calls)}
    every = [c for area in workflows.values() for c in area["calls"]]
    summary = {area: count(values["calls"]) for area, values in workflows.items()}
    summary["total"] = count(every)
    print("  workflow summary: " + json.dumps(summary), flush=True)
    return summary


