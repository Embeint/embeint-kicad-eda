def as_json(message):
    from google.protobuf import json_format
    return json_format.MessageToDict(message, preserving_proto_field_name=True)


def sorted_items(messages):
    """Items as JSON, in a stable order.  A global label's intersheet reference field and its
    fields-autoplaced flag are left out: KiCad recomputes and re-places that field after edits
    (annotation, for one) outside any undo step, so undo cannot restore them (seen live with both
    servers alike; a KiCad behaviour, not a server's)."""
    items = []
    for message in messages:
        item = as_json(message)
        if item.get("@type", "").endswith(".GlobalLabel"):
            item.pop("intersheet_refs_field", None)
            item.pop("fields_autoplaced", None)
        # KiCad's undo of a footprint edit gives back its pads and drawings in another order
        children = item.get("definition", {}).get("items")
        if isinstance(children, list):
            children.sort(key=lambda child: (json.dumps(child.get("id")), json.dumps(child, sort_keys=True)))
        items.append(item)
    return sorted(items, key=lambda item: json.dumps(item, sort_keys=True))


class Context:
    """What the workflows share: the KiCad client the harness checks with, the documents, a
    scratch folder (new for each run, the same path for both servers, emptied between them)."""

    def __init__(self, checker, spec, doc, board, board_doc, scratch):
        self.checker, self.spec, self.doc, self.board, self.board_doc = checker, spec, doc, board, board_doc
        self.scratch = scratch
        self.schematic = Tracked("schematic", checker, doc, lambda: sorted_items(checker.items(doc).items))
        self.pcb = Tracked("board", checker, board_doc, self.board_items)
        self.original = None  # state_of before the first workflow
        self.libraries_used = False  # the library workflow registered scratch libraries
        self.entries = None  # the report entries of the area running
        self.library_tables = {}  # live-demo's project library tables before the workflows

    def board_items(self):
        from board_client import ITEM_TYPES
        return sorted_items(self.checker.board_items(self.board_doc, [k for k in ITEM_TYPES if k != "pads"]))

    def board_settings(self):
        c, b = self.checker, self.board_doc
        return {"layers": c.board_layers(b), "stackup": c.board_stackup_layers(b), "rules": c.board_rules(b),
                "custom_rules": c.board_custom_rules(b), "netclasses": c.board_netclasses(b),
                "origins": c.board_origins(b), "page": c.page_layout(b), "grid": c.editor_grid(b)}

    def schematic_settings(self):
        return {"page": self.checker.page_layout(self.doc), "grid": self.checker.editor_grid(self.doc)}


def _project(ctx):
    """The project as the net class commands match it: with its trailing separator."""
    from client import types
    project = types.ProjectSpecifier()
    project.CopyFrom(ctx.board_doc.project)
    if project.path and not project.path.endswith(("/", "\\")):
        project.path += "\\" if "\\" in project.path and "/" not in project.path else "/"
    return project


def capture_raw_settings(ctx):
    """The board settings as KiCad's messages, to put back exactly: net classes and their
    assignments (the tools only merge them, none can remove one), custom rules, design rules and
    the stackup."""
    from board_design import bc, project_cmds
    c, project, b = ctx.checker, _project(ctx), ctx.board_doc
    return {"stackup": c.send(bc.GetBoardStackup(board=b), bc.BoardStackupResponse).stackup,
            "design rules": c.send(bc.GetBoardDesignRules(board=b), bc.BoardDesignRulesResponse).rules,
            "net classes": c.send(project_cmds.GetNetClasses(project=project), project_cmds.NetClassesResponse),
            "net class assignments": c.send(project_cmds.GetNetClassAssignments(project=project),
                                            project_cmds.NetClassAssignmentsResponse),
            "custom rules": c.send(bc.GetCustomDesignRules(board=b), bc.CustomRulesResponse)}


def restore_raw_settings(ctx, saved):
    """Put back the settings capture_raw_settings read that differ; returns their names."""
    from google.protobuf import empty_pb2
    from board_design import bc, project_cmds, types
    c, project, b = ctx.checker, _project(ctx), ctx.board_doc
    current = capture_raw_settings(ctx)
    changed = [name for name in saved if current[name] != saved[name]]
    if "stackup" in changed:
        c.send(bc.UpdateBoardStackup(board=b, stackup=saved["stackup"]), bc.BoardStackupResponse)
    if "design rules" in changed:
        c.send(bc.SetBoardDesignRules(board=b, rules=saved["design rules"]), bc.BoardDesignRulesResponse)
    if "net classes" in changed:
        c.send(project_cmds.SetNetClasses(project=project, net_classes=list(saved["net classes"].net_classes),
                                          merge_mode=types.MMM_REPLACE), empty_pb2.Empty)
    if "net class assignments" in changed:
        request = project_cmds.SetNetClassAssignments(project=project, merge_mode=types.MMM_REPLACE)
        request.assignments.extend(saved["net class assignments"].assignments)
        request.pattern_assignments.extend(saved["net class assignments"].pattern_assignments)
        c.send(request, empty_pb2.Empty)
    if "custom rules" in changed:
        c.send(bc.SetCustomDesignRules(board=b, rules=list(saved["custom rules"].rules)), bc.CustomRulesResponse)
    return changed


def restore_settings(ctx, baseline):
    """Put back the copper layers, origins, pages and grids that differ from the baseline (before
    restore_raw_settings: the stackup follows the copper layers); returns what was put back."""
    c, b = ctx.checker, ctx.board_doc
    board, put = baseline["board settings"], []
    if c.board_layers(b)["copper_layers"] != board["layers"]["copper_layers"]:
        c.board_layers(b, copper_layers=board["layers"]["copper_layers"])
        put.append("copper layers")
    if c.board_origins(b) != board["origins"]:
        c.board_origins(b, grid=board["origins"]["grid_origin_mm"], drill=board["origins"]["drill_origin_mm"])
        put.append("origins")
    for name, doc, settings in (("board", b, board), ("schematic", ctx.doc, baseline["schematic settings"])):
        page, grid = settings["page"], settings["grid"]
        if c.page_layout(doc) != page:
            block = page["title_block"]
            c.set_page(doc, size=page["paper"], orientation=page["orientation"], title=block["title"],
                       date=block["date"], revision=block["revision"], company=block["company"],
                       comments=block["comments"])
            put.append(f"{name} page")
        if c.editor_grid(doc) != grid:
            c.editor_grid(doc, preset_index=grid["preset_index"], style=grid["style"], visible=grid["visible"])
            put.append(f"{name} grid")
    return put


def restore(tracked, baseline, limit=80):
    """Undo with KiCad until the document equals its baseline; how many undo steps it took."""
    for step in range(limit + 1):
        if tracked.snapshot() == baseline:
            return step
        if not tracked.undo().get("performed", True):
            break
    raise WorkflowError(f"{tracked.name}: undo did not return to the baseline")


def state_of(ctx):
    """The documents and their settings.  ERC and DRC run first: their markers are not undoable
    and the page check counts them, so each server starts with the markers of the same document."""
    ctx.checker.erc(ctx.doc)
    ctx.checker.board_drc(ctx.board_doc, parity=False, refill=False)
    return {"schematic": ctx.schematic.snapshot(), "board": ctx.pcb.snapshot(),
            "schematic settings": ctx.schematic_settings(), "board settings": ctx.board_settings()}


# Settings the tools can only add to, which the harness puts back after each server
HARNESS_RESTORED = ("netclasses",)


def put_back(ctx, label, baseline, raw, finish):
    """Everything that follows one server's workflow, each part attempted whatever happened
    before it: the area's finish, KiCad's undo of both documents to their baseline, then the
    settings (those the workflow should have put back itself and did not are reported) and the
    raw board settings.  Returns what happened."""
    out = {"problems": [], "left": "", "steps": {}, "settings left": [], "put back": []}

    def attempt(what, action):
        try:
            return action()
        except Exception as error:  # noqa: BLE001 - reported; the remaining parts still run
            out["problems"].append(f"{what}: {type(error).__name__}: {error}")
            return None

    if finish:
        out["left"] = attempt("finish", lambda: finish(ctx, label)) or ""
    for name, tracked in (("schematic", ctx.schematic), ("board", ctx.pcb)):
        out["steps"][name] = attempt(f"{name} undo", lambda t=tracked, n=name: restore(t, baseline[n]))
    # Read as state_of reads them: after ERC and DRC, whose markers the page check counts
    current = attempt("settings", lambda: {k: v for k, v in state_of(ctx).items() if k.endswith("settings")}) or {}
    out["settings left"] = [f"{group}: {key}" for group, values in current.items() for key in values
                            if values[key] != baseline[group][key] and key not in HARNESS_RESTORED]
    out["put back"] += attempt("putting back the settings", lambda: restore_settings(ctx, baseline)) or []
    out["put back"] += attempt("putting back the board settings", lambda: restore_raw_settings(ctx, raw)) or []
    return out


# KiCad keeps the previous table as <table>.bak when it writes one
LIBRARY_TABLES = ("sym-lib-table", "fp-lib-table", "sym-lib-table.bak", "fp-lib-table.bak")


def library_tables(ctx):
    """live-demo's project library tables: their content, or None for a table that does not exist."""
    project = Path(ctx.spec["project"]["path"])
    return {name: (project / name).read_bytes() if (project / name).exists() else None for name in LIBRARY_TABLES}


def restore_library_tables(ctx, saved):
    """Put live-demo's project library tables and their backups back exactly (registering a
    project library writes them, creating them if absent); returns the names of those that differed."""
    project, changed = Path(ctx.spec["project"]["path"]), []
    for name, content in saved.items():
        path = project / name
        if (path.read_bytes() if path.exists() else None) != content:
            changed.append(name)
            if content is None:
                path.unlink()
            else:
                path.write_bytes(content)
    return changed


def remove_scratch_libraries(ctx):
    """Unregister any parity_ library left in the project tables; returns their nicknames."""
    removed = []
    for kind in ("symbol", "footprint"):
        for row in ctx.checker.library_table("project", kind):
            if row["nickname"].startswith("parity_"):
                ctx.checker.remove_library(row["nickname"], scope="project", kind=kind)
                removed.append(row["nickname"])
    return removed


def final_cleanup(ctx, tables):
    """At the end of the run, whatever happened: park both library editors on stock parts and
    unregister scratch libraries (before the scratch folder goes: the Footprint Editor watching a
    deleted folder opens a modal error on Windows), put the project library tables back, and
    delete the scratch folder.  Returns the problems."""
    from e2e_guard import park_footprint_editor
    problems = []

    def attempt(what, action):
        try:
            return action()
        except Exception as error:  # noqa: BLE001 - reported; the remaining parts still run
            problems.append(f"{what}: {type(error).__name__}: {error}")
            return None

    if ctx.libraries_used:
        attempt("parking the Footprint Editor", lambda: park_footprint_editor(ctx.checker))
        attempt("parking the Symbol Editor", lambda: ctx.checker.edit_symbol("Device:R"))
        left = attempt("unregistering scratch libraries", lambda: remove_scratch_libraries(ctx))
        if left:
            problems.append(f"scratch libraries were still registered: {left}")
    attempt("putting back the project library tables", lambda: restore_library_tables(ctx, tables))
    shutil.rmtree(ctx.scratch, ignore_errors=True)
    if ctx.scratch.exists():
        problems.append(f"the scratch folder {ctx.scratch} could not be removed")
    return problems


class WorkflowAbort(WorkflowError):
    """The documents could not be put back: the remaining areas would not start where they should."""


def run_area(area, workflow, finish, ctx, state, servers, server_env, endpoint, devnull, check, entries):
    """One area through each server in turn, then the comparison."""
    recordings, baselines = {}, {}
    for label, make in servers:
        baseline = state_of(ctx)
        raw = capture_raw_settings(ctx)
        baselines[label] = baseline
        recording, error = Recording(label, None), None
        try:
            recording.session = McpSession(make(server_env({"KICAD_API_SOCKET": endpoint})), devnull)
            try:
                workflow(recording, ctx, state)
            finally:
                recording.session.close()
        except Exception as failure:  # noqa: BLE001 - reported, then the documents are put back
            error = f"{type(failure).__name__}: {failure}"
        finally:
            outcome = put_back(ctx, label, baseline, raw, finish)
        after = state_of(ctx)
        steps = outcome["steps"]
